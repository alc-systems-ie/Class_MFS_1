#!/usr/bin/env python3
"""Generates bench credentials for a batch of MFS_1 devices - the pseudo Network Manager.

BENCH ONLY. Writes, into the gitignored secrets/ directory:
  - <serial>.conf for each device, a drop-in for credentials.conf:
        west build ... -- -DEXTRA_CONF_FILE=secrets/<serial>.conf
  - <batch>-credentials.xlsx, one row per device.

Every key comes from the operating system's CSPRNG (secrets module). Device IDs
are random, non-zero and unique within the batch. The script refuses to overwrite
an existing file: regenerating a flashed device's keys would lock it out until it
is reflashed.

Serial format (CLAUDE.md, owner 2026-09-15): MODEL-MMYY-NNNNN, the batch number
as 5 hex digits.

Run from the class_mfs_1 root, e.g. for ten devices made November 2026:
    python3 tools/gen_fleet_credentials.py --model MFS1 --mmyy 1126 --count 10
"""
import argparse
import os
import pathlib
import re
import secrets
import sys

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

M_KEY_BYTES = 32
M_ID_BYTES = 4
M_FONT = "Arial"


def serial_of(model: str, mmyy: str, index: int) -> str:
    return f"{model}-{mmyy}-{index:05X}"


def conf_text(serial: str, device_id: str, secret: str, provision: str) -> str:
    return "\n".join([
        f"# {serial} - generated by tools/gen_fleet_credentials.py. BENCH ONLY - never commit.",
        "# Build: west build -b nrf54l15dk/nrf54l05/cpuapp -p always -- "
        f"-DEXTRA_CONF_FILE=secrets/{serial}.conf",
        "",
        f'CONFIG_ALC_DEVICE_SERIAL="{serial}"',
        f'CONFIG_MFS_DEVICE_ID="{device_id}"',
        f'CONFIG_MFS_DEVICE_SECRET="{secret}"',
        f'CONFIG_MFS_PROVISION_KEY="{provision}"',
        "",
    ])


def write_workbook(path: pathlib.Path, batch: str, rows: list) -> None:
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Devices"
    headers = ["Serial", "Device ID (hex)", "Device secret (hex, 32 bytes)", "Provisioning key (hex, 32 bytes)", "Credentials file",
               "Flashed (date)", "Notes"]
    widths = [18, 16, 70, 70, 30, 14, 30]
    bold = Font(name=M_FONT, bold=True, color="FFFFFF")
    body = Font(name=M_FONT)
    mono = Font(name="Courier New")
    fill = PatternFill("solid", fgColor="1F3864")
    entry = PatternFill("solid", fgColor="FFF2CC")

    for column, (header, width) in enumerate(zip(headers, widths), start=1):
        cell = sheet.cell(row=1, column=column, value=header)
        cell.font = bold
        cell.fill = fill
        cell.alignment = Alignment(vertical="center")
        sheet.column_dimensions[cell.column_letter].width = width

    for offset, row in enumerate(rows, start=2):
        values = [row["serial"], row["id"], row["secret"], row["provision"], f"secrets/{row['serial']}.conf", None, None]
        for column, value in enumerate(values, start=1):
            cell = sheet.cell(row=offset, column=column, value=value)
            cell.font = mono if column in (2, 3, 4) else body
            if column in (6, 7):
                cell.fill = entry
    sheet.freeze_panes = "B2"

    notes = workbook.create_sheet("Read me")
    lines = [
        f"CLASS {batch} bench credentials - pseudo Network Manager",
        "",
        "CONFIDENTIAL. Anyone holding this file can derive every day key for these devices, command them,",
        "and set their clocks. Keep it in class_mfs_1/secrets/ (gitignored) or an encrypted store. Never email it.",
        "",
        "Device secret: derives every day key for that device (docs/tan-scheme.md).",
        "Provisioning key: authorises a time sync while the clock is invalid, and nothing else. Differs from the secret.",
        "Device ID: public; bound into every key derivation.",
        "",
        "To build a device: west build -b nrf54l15dk/nrf54l05/cpuapp -p always -- -DEXTRA_CONF_FILE=secrets/<serial>.conf",
        "Then flash with --recover (erases NVS) and provision the clock.",
        "",
        "Edit only the shaded columns (Flashed, Notes). The key columns are generated: do not retype them.",
        "Generated by tools/gen_fleet_credentials.py from the OS random source.",
        "",
        "BENCH ONLY: production provisions the keys into the nRF54L05 KMU, not the image (docs/tan-scheme.md section 8).",
    ]
    for index, line in enumerate(lines, start=1):
        cell = notes.cell(row=index, column=1, value=line)
        cell.font = Font(name=M_FONT, bold=(index == 1), size=12 if index == 1 else 10)
    notes.column_dimensions["A"].width = 120

    workbook.save(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", required=True, help="4-character model, e.g. MFS1")
    parser.add_argument("--mmyy", required=True, help="month and year made, e.g. 1126")
    parser.add_argument("--count", type=int, required=True, help="number of devices")
    parser.add_argument("--first", type=int, default=1, help="first batch number (default 1)")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Z0-9]{4}", args.model):
        sys.exit("--model must be 4 characters, A-Z / 0-9")
    if not re.fullmatch(r"(0[1-9]|1[0-2])[0-9]{2}", args.mmyy):
        sys.exit("--mmyy must be MMYY, e.g. 1126")
    if args.count < 1 or args.first < 1 or args.first + args.count - 1 > 0xFFFFF:
        sys.exit("--first/--count out of range")

    # Owner-only: these files hold device secrets. The umask covers the
    # workbook, which openpyxl creates itself.
    os.umask(0o077)

    here = pathlib.Path(__file__).resolve().parent.parent
    out_dir = here / "secrets"
    batch = f"{args.model}-{args.mmyy}"
    workbook_path = out_dir / f"{batch}-credentials.xlsx"
    serials = [serial_of(args.model, args.mmyy, args.first + offset) for offset in range(args.count)]

    existing = [p for p in [workbook_path] + [out_dir / f"{s}.conf" for s in serials] if p.exists()]
    if existing:
        sys.exit("Refusing to overwrite - a flashed device would be locked out:\n  " + "\n  ".join(str(p) for p in existing))

    out_dir.mkdir(mode=0o700, exist_ok=True)
    os.chmod(out_dir, 0o700)
    used_ids = set()
    rows = []
    for serial in serials:
        device_id = 0
        while device_id == 0 or device_id in used_ids:
            device_id = int.from_bytes(secrets.token_bytes(M_ID_BYTES), "big")
        used_ids.add(device_id)
        secret = secrets.token_hex(M_KEY_BYTES).upper()
        provision = secrets.token_hex(M_KEY_BYTES).upper()
        while provision == secret:
            provision = secrets.token_hex(M_KEY_BYTES).upper()
        row = {"serial": serial, "id": f"{device_id:08X}", "secret": secret, "provision": provision}
        rows.append(row)
        # O_EXCL makes the no-overwrite rule atomic, not just checked above.
        descriptor = os.open(out_dir / f"{serial}.conf", os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "w") as handle:
            handle.write(conf_text(serial, row["id"], secret, provision))

    write_workbook(workbook_path, batch, rows)
    print(f"Wrote {len(rows)} credential files and {workbook_path.relative_to(here)}.")
    for row in rows:
        print(f"  {row['serial']}  ID {row['id']}")


if __name__ == "__main__":
    main()
